"""Acceptance checks for the workshop. Standard library only.

    python checks/run_checks.py                  # everything
    python checks/run_checks.py --only hook      # one check: structure | hook | eval | names | commits

Green means the part is done. A red check says what is wrong in plain words. Do not edit this file: fix the plugin,
the prompt or the cases.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugin" / "p2p"
CASES = ROOT / "evals" / "cases"
RESULTS = ROOT / "evals" / "results"
MIN_CASES = 13          # the 13 provided cases; the workshop asks for 3 more of yours
MIN_ACCURACY = 0.80     # on the most recent run, which must cover every case
FORBIDDEN = ["Stratec", "SBS.DE", "DiaSorin", "QuidelOrtho", "CellaVision", "Mesa Labor", "Eurobio", "Diagnostics",
             "Medtech", "BioPharma", "Healthcare IT", "Consumer Health", "Healthcare Infra", "Life Science", "Animal & Environmental"]


NOTES: list = []


class Fail(Exception):
    pass


def expect(cond: bool, message: str) -> None:
    if not cond:
        raise Fail(message)


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


# --------------------------------------------------------------------------- checks
def check_structure() -> str:
    manifest = PLUGIN / ".claude-plugin" / "plugin.json"
    expect(PLUGIN.exists(), f"{rel(PLUGIN)} does not exist yet (Part 3 creates it)")
    expect(manifest.exists(), f"{rel(manifest)} is missing: only this file goes inside .claude-plugin/")
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise Fail(f"{rel(manifest)} is not valid JSON: {exc}")
    expect(re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", data.get("name", "")) is not None,
           f"plugin.json 'name' must be lowercase words joined by hyphens, got {data.get('name')!r}")
    skills = sorted((PLUGIN / "skills").glob("*/SKILL.md"))
    expect(len(skills) >= 2, f"found {len(skills)} skill(s) in {rel(PLUGIN / 'skills')}; the workshop asks for thesis and judge")
    for skill in skills:
        text = skill.read_text(encoding="utf-8")
        head = re.match(r"---\n(.*?)\n---", text, re.S)
        expect(head is not None, f"{rel(skill)} has no frontmatter (--- name / description ---)")
        expect(re.search(r"(?m)^name:\s*\S", head.group(1)) is not None, f"{rel(skill)}: frontmatter needs 'name:'")
        expect(re.search(r"(?m)^description:\s*\S", head.group(1)) is not None, f"{rel(skill)}: frontmatter needs 'description:'")
    note = ""
    if shutil.which("claude"):
        proc = subprocess.run(["claude", "plugin", "validate", str(PLUGIN)], capture_output=True, text=True, encoding="utf-8")
        expect(proc.returncode == 0, f"`claude plugin validate` failed:\n{(proc.stdout + proc.stderr).strip()[-800:]}")
        note = ", `claude plugin validate` passes"
    return f"{data['name']} with {len(skills)} skills: {', '.join(s.parent.name for s in skills)}{note}"


def _hook_commands() -> list:
    hooks_file = PLUGIN / "hooks" / "hooks.json"
    expect(hooks_file.exists(), f"{rel(hooks_file)} is missing (Part 3, the hook)")
    try:
        data = json.loads(hooks_file.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise Fail(f"{rel(hooks_file)} is not valid JSON: {exc}")
    entries = data.get("hooks", {}).get("PreToolUse", [])
    expect(entries, "hooks.json has no 'PreToolUse' entry: the guard must run BEFORE the write happens")
    commands = []
    for entry in entries:
        matcher = entry.get("matcher", "") or ""
        matches = matcher in ("", "*") or re.fullmatch(matcher, "Write") is not None
        if matches:
            commands += [h["command"] for h in entry.get("hooks", []) if h.get("type") == "command"]
    expect(commands, "no PreToolUse command hook whose matcher covers the Write tool (e.g. \"Write|Edit\")")
    return commands


def _run_hook(command: str, file_path: Path) -> tuple:
    cmd = command.replace("${CLAUDE_PLUGIN_ROOT}", str(PLUGIN)).replace("$CLAUDE_PLUGIN_ROOT", str(PLUGIN))
    cmd = cmd.replace("${CLAUDE_PROJECT_DIR}", str(ROOT)).replace("$CLAUDE_PROJECT_DIR", str(ROOT))
    payload = {"session_id": "check", "cwd": str(ROOT), "hook_event_name": "PreToolUse", "tool_name": "Write",
               "tool_input": {"file_path": str(file_path), "content": "tampered"}}
    env = {**os.environ, "CLAUDE_PLUGIN_ROOT": str(PLUGIN), "CLAUDE_PROJECT_DIR": str(ROOT)}
    argv = shlex.split(cmd, posix=(os.name != "nt"))
    if argv and not shutil.which(argv[0]):
        other = {"python": "python3", "python3": "python"}.get(argv[0])
        expect(other is not None and shutil.which(other) is not None,
               f"the hook command starts with '{argv[0]}', which is not installed here")
        NOTES.append(f"'{argv[0]}' is not installed on this machine, '{other}' is: write '{other}' in hooks.json for this machine")
        argv[0] = other
    proc = subprocess.run(argv, input=json.dumps(payload), capture_output=True,
                          text=True, encoding="utf-8", env=env, cwd=str(ROOT), timeout=30)
    denied = proc.returncode == 2
    if proc.returncode == 0 and proc.stdout.strip().startswith("{"):
        try:
            out = json.loads(proc.stdout)
            denied = out.get("hookSpecificOutput", {}).get("permissionDecision") == "deny" or out.get("decision") == "block"
        except json.JSONDecodeError:
            pass
    expect(proc.returncode in (0, 2), f"hook exited {proc.returncode} (only 0 = allow and 2 = block are meaningful; "
                                      f"anything else lets the write through):\n{(proc.stderr or proc.stdout).strip()[-500:]}")
    return denied, (proc.stderr or proc.stdout).strip()


def check_hook() -> str:
    commands = _hook_commands()
    golden = sorted(CASES.glob("*.json"))[0]
    for target in (golden, ROOT / "data" / "companies.csv"):
        denied = any(_run_hook(c, target)[0] for c in commands)
        expect(denied, f"the hook let a Write to {rel(target)} through: it must exit 2 (or answer permissionDecision deny)")
    allowed_target = ROOT / "prompts" / "judge_v2.md"
    denied, _ = _run_hook(commands[0], allowed_target)
    expect(not denied, f"the hook blocked a Write to {rel(allowed_target)}: prompts must stay editable, only data/ and evals/cases/ are frozen")
    _, message = _run_hook(commands[0], golden)
    expect(len(message) > 10, "the hook blocks but says nothing: write the reason on stderr so Claude (and the user) understand")
    note = f" ({NOTES[0]})" if NOTES else ""
    return f"blocks data/ and evals/cases/, lets prompts/ through; message: \"{message[:90]}\"{note}"


def check_eval() -> str:
    cases = sorted(CASES.glob("*.json"))
    expect(len(cases) >= MIN_CASES, f"{len(cases)} cases in {rel(CASES)}; keep the {MIN_CASES} provided ones")
    ids = set()
    for case in cases:
        try:
            data = json.loads(case.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise Fail(f"{rel(case)} is not valid JSON: {exc}")
        for key in ("id", "input", "expected", "why"):
            expect(key in data, f"{rel(case)} lacks the key '{key}'")
        expect(data["expected"] in ("Priority", "Radar", "Reject"), f"{rel(case)}: expected must be Priority, Radar or Reject")
        expect(data["id"] not in ids, f"duplicate case id {data['id']}")
        ids.add(data["id"])
    runs = sorted(RESULTS.glob("*.json"), key=lambda p: p.stat().st_mtime)
    expect(runs, f"no run in {rel(RESULTS)}: python evals/run.py")
    latest = json.loads(runs[-1].read_text(encoding="utf-8"))
    summary = latest["summary"]
    run_ids = {c["id"] for c in latest["cases"]}
    expect(ids <= run_ids, f"the latest run ({runs[-1].name}) does not cover every case: missing {sorted(ids - run_ids)[:3]}... rerun evals/run.py")
    expect(summary["accuracy"] >= MIN_ACCURACY, f"latest run {runs[-1].name}: accuracy {summary['accuracy']:.0%} < {MIN_ACCURACY:.0%}")
    return f"{len(cases)} cases; latest run {runs[-1].name}: {summary['accuracy']:.0%} with prompt {summary['prompt']}, model {summary['model']}"


def check_names() -> str:
    expect(PLUGIN.exists(), f"{rel(PLUGIN)} does not exist yet")
    hits = []
    for path in PLUGIN.rglob("*"):
        if path.is_file() and path.suffix in (".md", ".json", ".py", ".txt"):
            text = path.read_text(encoding="utf-8", errors="replace")
            hits += [f"{rel(path)}: {name}" for name in FORBIDDEN if name in text]  # case-sensitive: team and company names
    expect(not hits, "the sector is a setting, not code; names found in the plugin:\n  " + "\n  ".join(hits[:6]))
    return "no company, ticker or team name in the plugin"


def check_commits() -> str:
    if not shutil.which("git"):
        return "git not installed: skipped"
    proc = subprocess.run(["git", "rev-parse", "--abbrev-ref", "HEAD"], capture_output=True, text=True, cwd=str(ROOT))
    expect(proc.returncode == 0, "not a git repository")
    branch = proc.stdout.strip()
    expect(branch != "main", "you are on main: work on your own branch (git switch -c hackathon/<your-name>)")
    log = subprocess.run(["git", "log", "--oneline", "main..HEAD"], capture_output=True, text=True, cwd=str(ROOT))
    commits = [l for l in log.stdout.splitlines() if l.strip()]
    expect(len(commits) >= 3, f"{len(commits)} commit(s) on {branch}: one commit per eval iteration, please (at least 3)")
    return f"branch {branch}, {len(commits)} commits"


CHECKS = {"structure": check_structure, "hook": check_hook, "eval": check_eval, "names": check_names, "commits": check_commits}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", help="comma-separated: " + ", ".join(CHECKS))
    args = ap.parse_args()
    names = [n.strip() for n in args.only.split(",")] if args.only else list(CHECKS)
    failed = 0
    for name in names:
        expect(name in CHECKS, f"unknown check {name}")
        try:
            detail = CHECKS[name]()
            print(f"  OK   {name:<10} {detail}")
        except Fail as exc:
            failed += 1
            print(f"  KO   {name:<10} {exc}")
        except Exception as exc:  # noqa: BLE001
            failed += 1
            print(f"  KO   {name:<10} crashed: {type(exc).__name__}: {exc}")
    print(f"\n{len(names) - failed}/{len(names)} checks green")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
